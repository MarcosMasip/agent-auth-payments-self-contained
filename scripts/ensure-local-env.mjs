#!/usr/bin/env node
/**
 * ensure-local-env.mjs
 * Creates minimal .env (web) and .env (agents) files for self-contained local mode if they do not exist.
 * Idempotent: will not overwrite existing keys unless --force is passed.
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const FORCE = process.argv.includes('--force');

// Determine repo root relative to this script's directory, so calls from any CWD behave consistently.
const scriptDir = dirname(fileURLToPath(import.meta.url));
const root = resolve(scriptDir, '..');
const webDir = resolve(root, 'apps/web');
const agentsDir = resolve(root, 'apps/agents');

function loadEnvFile(path) {
  if (!existsSync(path)) return {};
  const lines = readFileSync(path, 'utf8').split(/\r?\n/);
  const map = {};
  for (const l of lines) {
    if (!l.trim() || l.trim().startsWith('#')) continue;
    const idx = l.indexOf('=');
    if (idx === -1) continue;
    const key = l.slice(0, idx).trim();
    let val = l.slice(idx + 1).trim();
    if (val.startsWith('"') && val.endsWith('"')) val = val.slice(1, -1);
    map[key] = val;
  }
  return map;
}

function writeEnvFile(path, merged, header) {
  const sortedKeys = Object.keys(merged).sort();
  const body = sortedKeys.map(k => `${k}=${/\s/.test(merged[k]) ? '"' + merged[k] + '"' : merged[k]}`).join('\n');
  writeFileSync(path, `${header}\n${body}\n`, 'utf8');
}

function ensureDir(p) { mkdirSync(dirname(p), { recursive: true }); }

const sharedDefaults = {
  LOCAL_MODE: 'true',
  LOCAL_JWT_SECRET: 'dev_local_jwt_secret_change_me'
};

const webDefaults = {
  NEXT_PUBLIC_LOCAL_MODE: 'true',
  DATABASE_URL: 'file:./.data/dev.db',
  NEXT_PUBLIC_API_URL: 'http://localhost:2025',
  NEXT_PUBLIC_ASSISTANT_ID: 'agent',
  NEXT_PUBLIC_BASE_URL: 'http://localhost:3000',
  NEXT_PUBLIC_GOOGLE_AUTH_DISABLED: 'true'
};

const agentsDefaults = {
};

function ensureEnv(appDir, filename, defaults) {
  const path = resolve(appDir, filename);
  const current = loadEnvFile(path);
  const merged = { ...defaults, ...sharedDefaults };
  // Preserve existing values unless FORCE
  for (const k of Object.keys(current)) {
    if (!FORCE && current[k] !== undefined) merged[k] = current[k];
  }
  // Auto-correct common legacy port mismatch (2024 -> 2025) for self-contained mode
  if (
    !FORCE &&
    merged.LOCAL_MODE === 'true' &&
    typeof merged.NEXT_PUBLIC_API_URL === 'string' &&
    /:2024(\/$|$)/.test(merged.NEXT_PUBLIC_API_URL)
  ) {
    merged.NEXT_PUBLIC_API_URL = 'http://localhost:2025';
  }
  const header = `# Generated by scripts/ensure-local-env.mjs (${new Date().toISOString()})\n# Use --force to regenerate defaults`;
  ensureDir(path);
  writeEnvFile(path, merged, header);
  console.log(`✔ Ensured ${path}`);
}

ensureEnv(webDir, '.env', { ...webDefaults });
ensureEnv(agentsDir, '.env', { ...agentsDefaults });

// Provide guidance for developers
console.log('\nSelf-contained environment ready.');
console.log('- Edit apps/web/.env and apps/agents/.env to customize.');
console.log('- Re-run with --force to reset defaults.');
